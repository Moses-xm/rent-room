// 将老数据中的 cover 字段（JSON 数组字符串）转为单个路径，并去除 /public 前缀
function parseCover(raw: string): string {
  const arr = JSON.parse(raw) as string[];
  return arr[0].replace('/public', '');
}

// 将老数据中的 images 字段（JSON 数组字符串）去除每项的 /public 前缀，保持 JSON 字符串格式
function parseImages(raw: string): string {
  const arr = JSON.parse(raw) as string[];
  return JSON.stringify(arr.map((p) => p.replace('/public', '')));
}

// 老数据中时间戳为毫秒字符串，转为 Date；null 原样返回
function parseTime(ts: string | null): Date | null {
  return ts ? new Date(Number(ts)) : null;
}

